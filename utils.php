function markdown_escape($text) {
  $text = str_replace(['.', '+', '-', /*'(', ')',*/ '!', '='], ['\.', '\+', '\-', /*'\(', '\)',*/ '\!', '\='], $text);
  // экранируем скобки только если есть мэтч по пробелу
  if(preg_match("# \(([^)]*)\)#", $text)) {
    $text = preg_replace("# \(([^)]*)\)#", " \($1\)", $text);
  }
  return $text;
}

