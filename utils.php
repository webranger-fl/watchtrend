function resolveSwitchValue($item, $field) {
  if($item) return $item[$field['key']] == true;
  if($field && isset($field['value'])) return $field['value'];
  return false;
}

function searchForType($id, $array) {
  foreach ($array as $key => $val) {
      if ($val['type'] === $id) {
          return $key;
      }
  }
  return null;
}

