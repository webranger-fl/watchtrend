}

function formatNumber($number) {
    // Если число меньше 1000, возвращаем как есть
    if ($number < 1000) {
        return $number;
    }
    
    // Миллиарды
    if ($number >= 1000000000) {
        $result = $number / 1000000000;
        $formatted = number_format($result, 2, '.', '');
        // Убираем лишние нули
        $formatted = rtrim(rtrim($formatted, '0'), '.');
        return $formatted . ' млрд';
    }
    
    // Миллионы
    if ($number >= 1000000) {
        $result = $number / 1000000;
        $formatted = number_format($result, 2, '.', '');
        // Убираем лишние нули
        $formatted = rtrim(rtrim($formatted, '0'), '.');
        return $formatted . ' млн';
    }
    
    // Тысячи
    if ($number >= 1000) {
        $result = $number / 1000;
        $formatted = number_format($result, 2, '.', '');
        // Убираем лишние нули
        $formatted = rtrim(rtrim($formatted, '0'), '.');
        return $formatted . ' тыс';
    }
    
    return $number;
}

