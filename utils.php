function calcPercentChange($stat, $prevStat) {
  if($stat->count === 0 && $prevStat->count === 0) return 0;
  if($prevStat->count === 0) return 100;
  return round((($stat->count - $prevStat->count) / ($prevStat->count)) * 100);
}

